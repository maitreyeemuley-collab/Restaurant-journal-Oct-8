/**
 * Generates supabase/migrations/0002_seed_catalog.sql from the TypeScript seed so the
 * database catalog and src/data/seed.ts can never drift apart.
 *
 *   npm run db:catalog
 */
import { buildSeed } from '../src/data/seed'

const text = (value: string): string => `'${value.replaceAll("'", "''")}'`
const array = (values: readonly string[]): string =>
  values.length === 0 ? "'{}'::text[]" : `array[${values.map(text).join(', ')}]::text[]`

const { catalog } = buildSeed(new Date())

const rows = catalog.map(
  (c) =>
    `  (${[
      text(c.id),
      text(c.name),
      text(c.neighborhood),
      text(c.cuisine),
      String(c.priceLevel),
      text(c.blurb),
      array(c.tags),
      array(c.occasions),
      array(c.dietaryOptions),
      String(c.isNew),
      String(c.isTrending),
      String(c.lat),
      String(c.lng),
      text(c.createdAt),
    ].join(', ')})`,
)

console.log(`-- Generated by scripts/generate-catalog-sql.ts. Safe to run more than once.
-- Run this in the Supabase SQL Editor AFTER 0001_init.sql.

insert into public.catalog_places
  (id, name, neighborhood, cuisine, price_level, blurb, tags, occasions, dietary_options,
   is_new, is_trending, lat, lng, created_at)
values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  neighborhood = excluded.neighborhood,
  cuisine = excluded.cuisine,
  price_level = excluded.price_level,
  blurb = excluded.blurb,
  tags = excluded.tags,
  occasions = excluded.occasions,
  dietary_options = excluded.dietary_options,
  is_new = excluded.is_new,
  is_trending = excluded.is_trending,
  lat = excluded.lat,
  lng = excluded.lng;
`)
